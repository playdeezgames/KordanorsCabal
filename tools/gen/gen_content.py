# Content exporter (task 27, decision D8): reads src/KordanorsCabal/boilerplate.db and writes
#   odin/game/content_enums.odin  - an enum per content table (value = database id, 0 = None) plus the Check and Action event enums
#   odin/game/content_data.odin   - the definition tables, with the relation tables folded into the definitions
# Deterministic: running it twice gives identical files (tools/test.sh checks this).
import os, re, sqlite3
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
db = sqlite3.connect(os.path.join(ROOT, "src", "KordanorsCabal", "boilerplate.db"))
q = lambda sql, *a: db.execute(sql, a).fetchall()

def ident(name, id_, seen):
    s = re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_") or f"Id_{id_}"
    if s[0].isdigit(): s = "_" + s
    if s in seen: s = f"{s}_{id_}"
    seen.add(s)
    return s
def snake(name): return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
def esc(t): return '"' + t.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

ENUMS = [  # enum, table, id column, name column
    ("Item_Type", "ItemTypes", "ItemTypeId", "ItemTypeName"), ("Character_Type", "CharacterTypes", "CharacterTypeId", "CharacterTypeName"),
    ("Location_Type", "LocationTypes", "LocationTypeId", "LocationTypeName"), ("Feature_Type", "FeatureTypes", "FeatureTypeId", "FeatureTypeName"),
    ("Equip_Slot", "EquipSlots", "EquipSlotId", "EquipSlotName"), ("Direction", "Directions", "DirectionId", "DirectionName"),
    ("Stat", "StatisticTypes", "StatisticTypeId", "CharacterStatisticTypeName"), ("Dungeon_Level", "DungeonLevels", "DungeonLevelId", "DungeonLevelName"),
    ("Shoppe_Type", "ShoppeTypes", "ShoppeTypeId", "ShoppeTypeName"), ("Spell_Type", "SpellTypes", "SpellTypeId", "SpellTypeName"),
]
names = {}   # enum -> {id: identifier}
out = ["package game", "", "// GENERATED by tools/gen/gen_content.py from src/KordanorsCabal/boilerplate.db. Do not edit.", ""]
for enum, table, idc, namec in ENUMS:
    seen, names[enum] = {"None"}, {}
    out.append(f"{enum} :: enum u8 {{\n\tNone = 0,")
    for id_, nm in q(f"select {idc},{namec} from {table} order by 1"):
        names[enum][id_] = ident(nm, id_, seen)
        out.append(f"\t{names[enum][id_]} = {id_},")
    out.append("}\n")
# route and quest types have no name column: name them by id
names["Route_Type"] = {i: f"Route_{i}" for (i,) in q("select RouteTypeId from RouteTypes")}
out.append("Route_Type :: enum u8 {\n\tNone = 0,\n" + "".join(f"\tRoute_{i} = {i},\n" for i in names["Route_Type"]) + "}\n")
names["Quest_Type"] = {1: "Cellar_Rats"}
assert q("select count(*) from QuestTypes")[0][0] == 1
out.append("Quest_Type :: enum u8 {\n\tNone = 0,\n\tCellar_Rats = 1,\n}\n")
out.append("// The player modes (Constants.PlayerModes in the VB game), stored in the save.\nPlayer_Mode :: enum u8 {\n\tNone = 0, Neutral, Turn, Move, Elder, InnKeeper, TownDrunk, Chicken, BlackMarket, BlackMage, Blacksmith, Constable, Healer,\n}\n")

# events: separate enums for checks and actions (D18)
checks, actions = set(), set()
for t, e, n in q("select ItemTypeId, EventId, EventName from ItemTypeEvents"):
    if e == 5: continue   # add-to-inventory: unused (D13)
    (checks if e == 2 else actions).add(snake(n))
for c, a in q("select [CastCheck],[Cast] from SpellTypes"): checks.add(snake(c)); actions.add(snake(a))
for ca, a, cc, c in q("select CanAcceptEventName,AcceptEventName,CanCompleteEventName,CompleteEventName from QuestTypes"):
    checks.update([snake(ca), snake(cc)]); actions.update([snake(a), snake(c)])
actions.add("Location_Decay_Items")
out.append("Check :: enum u8 {\n\tNone,\n" + "".join(f"\t{c},\n" for c in sorted(checks)) + "}\n")
out.append("Action :: enum u8 {\n\tNone,\n" + "".join(f"\t{a},\n" for a in sorted(actions)) + "}\n")
open(os.path.join(ROOT, "odin", "game", "content_enums.odin"), "w").write("\n".join(out))

# ---------------------------------------------------------------------------------------------------- data
N = names
def dice(txt):
    m = re.fullmatch(r"(\d+)d(\d+)", txt); assert m, txt
    return f"{{{m.group(1)}, {m.group(2)}}}"
def maybe(v): return "nil" if v is None else str(v)
def bitset(enum, ids): return f"{{{', '.join('.' + N[enum][i] for i in sorted(ids))}}}"
d = ["package game", "", "// GENERATED by tools/gen/gen_content.py from src/KordanorsCabal/boilerplate.db. Do not edit.", ""]

# statistic ids used in item statistics
S = {i: n for i, n in q("select StatisticTypeId, CharacterStatisticTypeName from StatisticTypes")}
STAT_FIELD = {"Encumbrance": "encumbrance", "AttackDice": "attack_dice", "MaximumDamage": "max_damage", "DefendDice": "defend_dice",
              "MaximumDurability": "max_durability", "Offer": "offer", "Price": "price", "RepairPrice": "repair_price", "SingleUse": "single_use"}
stats_by_item, events_by_item = {}, {}
for t, s_, v in q("select ItemTypeId, StatisticTypeId, StatisticValue from ItemTypeStatistics"): stats_by_item.setdefault(t, {})[STAT_FIELD[S[s_]]] = v
for t, e, n in q("select ItemTypeId, EventId, EventName from ItemTypeEvents"):
    if e != 5: events_by_item.setdefault(t, {})[{1: "purify", 2: "can_use", 3: "use", 4: "decay"}[e]] = snake(n)
equip, shops, spawn_dice, spawn_loc, buffs = {}, {}, {}, {}, {}
for t, s_ in q("select ItemTypeId, EquipSlotId from ItemTypeEquipSlots"): equip.setdefault(t, set()).add(s_)
TX = {1: "Offer", 2: "Price", 3: "Repair"}
for t, sh, tx in q("select ItemTypeId, ShoppeTypeId, TransactionTypeId from ItemTypeShopTypes"): shops.setdefault(t, {}).setdefault(sh, set()).add(TX[tx])
for t, lv, dc in q("select ItemTypeId, DungeonLevelId, SpawnDice from ItemTypeSpawnCounts"): spawn_dice.setdefault(t, {})[lv] = dc
for t, lv, lt in q("select ItemTypeId, DungeonLevelId, LocationTypeId from ItemTypeSpawnLocationTypes"): spawn_loc.setdefault(t, {}).setdefault(lv, set()).add(lt)
for t, st, b in q("select ItemTypeId, StatisticTypeId, Buff from ItemTypeCharacterStatisticBuffs"): buffs.setdefault(t, {})[st] = b

d.append("ITEM_TYPES := #partial [Item_Type]Item_Type_Def{")
for t, nm in q("select ItemTypeId, ItemTypeName from ItemTypes order by 1"):
    st = stats_by_item.get(t, {})
    fields = []
    for f in STAT_FIELD.values():
        if f in st:
            v = st[f]
            fields.append(f"{f} = {'true' if v else 'false'}" if f == "single_use" else f"{f} = {v}")
    parts = [f"name = {esc(nm)}", f"stats = {{{', '.join(fields)}}}"]
    if t in equip: parts.append(f"equip = {bitset('Equip_Slot', equip[t])}")
    if t in events_by_item: parts.append("events = {" + ", ".join(f"{k} = .{v}" for k, v in events_by_item[t].items()) + "}")
    if t in shops: parts.append("shops = #partial {" + ", ".join(f".{N['Shoppe_Type'][sh]} = {{{', '.join('.' + x for x in sorted(txs))}}}" for sh, txs in sorted(shops[t].items())) + "}")
    levels = sorted(set(spawn_dice.get(t, {})) | set(spawn_loc.get(t, {})))   # some items have places to go but no dice (keys are placed by the world generator)
    if levels:
        entries = []
        for lv in levels:
            dc = spawn_dice.get(t, {}).get(lv)
            entries.append(f".{N['Dungeon_Level'][lv]} = {{" + (f"dice = {dice(dc)}, " if dc else "") + f"locations = {bitset('Location_Type', spawn_loc.get(t, {}).get(lv, set()))}}}")
        parts.append("spawn = #partial {" + ", ".join(entries) + "}")
    if t in buffs: parts.append("buffs = #partial {" + ", ".join(f".{N['Stat'][st_]} = {b}" for st_, b in sorted(buffs[t].items())) + "}")
    d.append(f"\t.{N['Item_Type'][t]} = {{{', '.join(parts)}}},")
d.append("}\n")

# characters
init, att, bribes, enemies, loot, shots, sc, sl = {}, {}, {}, {}, {}, {}, {}, {}
for c_, st, v in q("select CharacterTypeId, StatisticTypeId, InitialValue from CharacterTypeInitialStatistics"): init.setdefault(c_, {})[st] = v
# A statistic with no row reads as its type's default value in the VB game (StatisticType.DefaultValue), so resolve that here
defaults = {i: df for i, df in q("select StatisticTypeId, DefaultValue from StatisticTypes") if df is not None}
for c_ in [r[0] for r in q("select CharacterTypeId from CharacterTypes")]:
    row = init.setdefault(c_, {})
    for st, df in defaults.items(): row.setdefault(st, df)
init = {c_: {st: v for st, v in row.items() if v != 0} for c_, row in init.items()}   # zero is the array's default
for c_, a, w in q("select CharacterTypeId, AttackType, Weight from CharacterTypeAttackTypes"): att.setdefault(c_, {})[a] = w
for c_, i in q("select CharacterTypeId, ItemTypeId from CharacterTypeBribes"): bribes.setdefault(c_, set()).add(i)
for c_, e in q("select CharacterTypeId, EnemyCharacterTypeId from CharacterTypeEnemies"): enemies.setdefault(c_, set()).add(e)
for c_, i, w in q("select CharacterTypeId, ItemTypeId, Weight from CharacterTypeLoots order by rowid"): loot.setdefault(c_, []).append((i, w))
for c_, tx, w in q("select CharacterTypeId, PartingShot, Weight from CharacterTypePartingShots order by rowid"): shots.setdefault(c_, []).append((tx, w))
for c_, lv, n in q("select CharacterTypeId, DungeonLevelId, SpawnCount from CharacterTypeSpawnCounts"): sc.setdefault(c_, {})[lv] = n
for c_, lv, lt in q("select CharacterTypeId, DungeonLevelId, LocationTypeId from CharacterTypeSpawnLocations"): sl.setdefault(c_, {}).setdefault(lv, set()).add(lt)
ATT = {1: "Physical", 2: "Mental"}
for c_ in loot: pass
MAX_LOOT, MAX_SHOTS = 4, 2   # must equal MAX_LOOT and MAX_PARTING_SHOTS in content.odin
assert all(len(v) <= MAX_LOOT for v in loot.values()) and all(len(v) <= MAX_SHOTS for v in shots.values())
d.append("\nCHARACTER_TYPES := #partial [Character_Type]Character_Type_Def{")
for c_, nm, xp, md, und in q("select CharacterTypeId, CharacterTypeName, XPValue, MoneyDropDice, IsUndead from CharacterTypes order by 1"):
    parts = [f"name = {esc(nm)}", f"xp_value = {xp}", f"money_dice = {dice(md)}", f"is_undead = {'true' if und else 'false'}"]
    if c_ in init: parts.append("initial_stats = #partial {" + ", ".join(f".{N['Stat'][st]} = {v}" for st, v in sorted(init[c_].items())) + "}")
    if c_ in att: parts.append("attack_weights = #partial {" + ", ".join(f".{ATT[a]} = {w}" for a, w in sorted(att[c_].items())) + "}")
    if c_ in bribes: parts.append(f"bribes = {bitset('Item_Type', bribes[c_])}")
    if c_ in enemies: parts.append(f"enemies = {bitset('Character_Type', enemies[c_])}")
    if c_ in loot: parts.append("loot = {" + ", ".join(f"{k} = {{.{N['Item_Type'][i] if i else 'None'}, {w}}}" for k, (i, w) in enumerate(loot[c_])) + "}")
    if c_ in shots: parts.append("parting_shots = {" + ", ".join(f"{k} = {{{esc(tx)}, {w}}}" for k, (tx, w) in enumerate(shots[c_])) + "}")
    if c_ in sc: parts.append("spawn_count = #partial {" + ", ".join(f".{N['Dungeon_Level'][lv]} = {n}" for lv, n in sorted(sc[c_].items())) + "}")
    if c_ in sl: parts.append("spawn_locations = #partial {" + ", ".join(f".{N['Dungeon_Level'][lv]} = {bitset('Location_Type', lts)}" for lv, lts in sorted(sl[c_].items())) + "}")
    d.append(f"\t.{N['Character_Type'][c_]} = {{{', '.join(parts)}}},")
d.append("}\n")

# small tables
d.append("STATS := #partial [Stat]Stat_Def{")
for i, nm, ab, mn, df, mx in q("select StatisticTypeId, CharacterStatisticTypeName, Abbreviation, MinimumValue, DefaultValue, MaximumValue from StatisticTypes order by 1"):
    d.append(f"\t.{N['Stat'][i]} = {{{esc(nm)}, {esc(ab)}, {mn}, {maybe(df)}, {mx}}},")
d.append("}\n")
d.append("DIRECTIONS := #partial [Direction]Direction_Def{")
for i, nm, ab, card, prev, opp, nxt in q("select DirectionId, DirectionName, Abbreviation, IsCardinal, PreviousDirectionId, OppositeDirectionId, NextDirectionId from Directions order by 1"):
    f = lambda x: "." + N["Direction"][x] if x else ".None"
    d.append(f"\t.{N['Direction'][i]} = {{{esc(nm)}, {esc(ab)}, {'true' if card else 'false'}, {f(prev)}, {f(opp)}, {f(nxt)}}},")
d.append("}\n")
d.append("LOCATION_TYPES := #partial [Location_Type]Location_Type_Def{")
for i, nm, dg, cm, mp in q("select LocationTypeId, LocationTypeName, IsDungeon, CanMap, RequiresMP from LocationTypes order by 1"):
    d.append(f"\t.{N['Location_Type'][i]} = {{{esc(nm)}, {'true' if dg else 'false'}, {'true' if cm else 'false'}, {'true' if mp else 'false'}}},")
d.append("}\n")
d.append("FEATURE_TYPES := #partial [Feature_Type]Feature_Type_Def{")
for i, nm, lt, mode in q("select FeatureTypeId, FeatureTypeName, LocationTypeId, InteractionMode from FeatureTypes order by 1"):
    d.append(f"\t.{N['Feature_Type'][i]} = {{{esc(nm)}, .{N['Location_Type'][lt]}, {mode}}},")
d.append("}\n")
locks = {r: (u, it) for r, u, it in q("select RouteTypeId, UnlockedRouteTypeId, UnlockItemTypeId from RouteTypeLocks")}
d.append("ROUTE_TYPES := #partial [Route_Type]Route_Type_Def{")
for i, ab, single in q("select RouteTypeId, Abbreviation, IsSingleUse from RouteTypes order by 1"):
    u, it = locks.get(i, (None, None))
    d.append(f"\t.{N['Route_Type'][i]} = {{{esc(ab)}, {'true' if single else 'false'}, .{N['Route_Type'][u] if u else 'None'}, .{N['Item_Type'][it] if it else 'None'}}},")
d.append("}\n")
power = {}
for sp, lv, pw in q("select SpellTypeId, SpellLevel, Power from SpellTypeRequiredPowers"): power.setdefault(sp, [0, 0])[lv] = pw
d.append("SPELL_TYPES := #partial [Spell_Type]Spell_Type_Def{")
for i, nm, ml, cc, ca in q("select SpellTypeId, SpellTypeName, MaximumLevel, [CastCheck], [Cast] from SpellTypes order by 1"):
    d.append(f"\t.{N['Spell_Type'][i]} = {{{esc(nm)}, {ml}, .{snake(cc)}, .{snake(ca)}, {{{power[i][0]}, {power[i][1]}}}}},")
d.append("}\n")
d.append("QUEST_TYPES := #partial [Quest_Type]Quest_Type_Def{")
for i, a, b, c, e in q("select QuestTypeId, CanAcceptEventName, AcceptEventName, CanCompleteEventName, CompleteEventName from QuestTypes"):
    d.append(f"\t.Cellar_Rats = {{.{snake(a)}, .{snake(b)}, .{snake(c)}, .{snake(e)}}},")
d.append("}\n")
d.append("SHOPPE_TYPE_NAME := [Shoppe_Type]string{.None = \"\", " + ", ".join(f".{N['Shoppe_Type'][i]} = {esc(nm)}" for i, nm in q("select ShoppeTypeId, ShoppeTypeName from ShoppeTypes order by 1")) + "}\n")
d.append("EQUIP_SLOT_NAME := [Equip_Slot]string{.None = \"\", " + ", ".join(f".{N['Equip_Slot'][i]} = {esc(nm)}" for i, nm in q("select EquipSlotId, EquipSlotName from EquipSlots order by 1")) + "}\n")
d.append("DUNGEON_LEVEL_NAME := [Dungeon_Level]string{.None = \"\", " + ", ".join(f".{N['Dungeon_Level'][i]} = {esc(nm)}" for i, nm in q("select DungeonLevelId, DungeonLevelName from DungeonLevels order by 1")) + "}\n")
lores = q("select LoreId, ItemName, LoreText from Lores order by 1")
d.append(f"LORE_COUNT :: {len(lores)}")
d.append("LORES := [LORE_COUNT + 1]Lore_Def{{}, " + ", ".join(f"{{{esc(n)}, {esc(t)}}}" for _, n, t in lores) + "}\n")
# row counts of the folded tables, so a test can prove nothing was lost in folding
counts = {t: q(f"select count(*) from {t}")[0][0] for t in ["ItemTypeStatistics", "ItemTypeEquipSlots", "ItemTypeShopTypes", "ItemTypeSpawnCounts", "ItemTypeSpawnLocationTypes",
          "ItemTypeCharacterStatisticBuffs", "CharacterTypeInitialStatistics", "CharacterTypeAttackTypes", "CharacterTypeBribes", "CharacterTypeEnemies", "CharacterTypeLoots",
          "CharacterTypePartingShots", "CharacterTypeSpawnCounts", "CharacterTypeSpawnLocations", "ItemTypes", "CharacterTypes", "Lores"]}
d.append("// Row counts of the source tables that were folded into the definitions above (checked by a test).\nSOURCE_ROWS :: struct { " + ", ".join(f"{snake(k).lower()}: int" for k in counts) + " }{" + ", ".join(f"{snake(k).lower()} = {v}" for k, v in counts.items()) + "}")
written = {
    "equip_bits": sum(len(v) for v in equip.values()), "shop_pairs": sum(len(txs) for v in shops.values() for txs in v.values()),
    "item_spawn_levels": sum(len(v) for v in spawn_dice.values()), "item_spawn_location_bits": sum(len(x) for v in spawn_loc.values() for x in v.values()),
    "buff_entries": sum(len(v) for v in buffs.values()), "initial_stat_entries": sum(len(v) for v in init.values()),
    "attack_entries": sum(len(v) for v in att.values()), "bribe_bits": sum(len(v) for v in bribes.values()), "enemy_bits": sum(len(v) for v in enemies.values()),
    "loot_entries": sum(len(v) for v in loot.values()), "parting_shots": sum(len(v) for v in shots.values()),
    "character_spawn_levels": sum(len(v) for v in sc.values()), "character_spawn_location_bits": sum(len(x) for v in sl.values() for x in v.values()),
}
d.append("// Number of entries the generator wrote into each folded table (a test recounts them from the definitions).\nWRITTEN :: struct { " + ", ".join(f"{k}: int" for k in written) + " }{" + ", ".join(f"{k} = {v}" for k, v in written.items()) + "}")
open(os.path.join(ROOT, "odin", "game", "content_data.odin"), "w").write("\n".join(d) + "\n")
