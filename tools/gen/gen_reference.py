# Writes odin/tests/reference_data.odin from docs/reference/vb: the recorded VB screens (exact cells and frame hashes),
# compiled into the test program so the same tests run natively and under wasm (no file access on wasm).
import os
HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, "..", "..", "docs", "reference", "vb")
out = ["package main", "", "// GENERATED by tools/gen/gen_reference.py from docs/reference/vb. A cell is glyph | hue << 8 | inverted << 16.", "",
       "Reference_Screen :: struct { name: string, hash: u64, cells: [22 * 23]u32 }", "", "REFERENCE_SCREENS := []Reference_Screen{"]
names = [l.split()[1] for l in open(os.path.join(REF, "_log.txt")) if l.startswith("snap ")]
for n in names:
    cells = []
    for row in open(os.path.join(REF, n + ".cells")).read().strip().split("\n"):
        for tok in row.split():
            g, h, i = map(int, tok.split("."))
            cells.append(g | h << 8 | i << 16)
    assert len(cells) == 22 * 23, n
    h = int(open(os.path.join(REF, n + ".hash")).read().strip(), 16)
    out.append(f'\t{{"{n}", 0x{h:016x}, {{' + ", ".join(map(str, cells)) + "}},")
out.append("}")
open(os.path.join(HERE, "..", "..", "odin", "tests", "reference_data.odin"), "w").write("\n".join(out) + "\n")
print(len(names), "reference screens")
