#!/usr/bin/env python3
"""Writes odin/game/ui_data.odin from the VB UI sources: the Pattern names (as the Odin enum Glyph, whose values are the glyph
indices used by font_data.odin), the character and route sprites (CharacterSprites.vb, RouteSprites.vb) and where each item type
is drawn on the dungeon floor (ItemTypeUIDescriptor.vb). Run from anywhere; tools/test.sh checks the output is current."""
import re, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ui = os.path.join(root, "src", "KordanorsCabal.UI")
rd = lambda p: open(p, encoding="utf-8-sig").read()

def snake(name):  # VB identifier -> the Odin enum member spelling used by gen_content.py (LightOrange -> Light_Orange)
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)

enums = rd(os.path.join(root, "odin", "game", "content_enums.odin"))
def enum_names(enum):
    body = re.search(enum + r" :: enum u8 \{(.*?)\n\}", enums, re.S).group(1)
    return {int(i): n for n, i in re.findall(r"(\w+) = (\d+),", body)}
character_names = enum_names("Character_Type")
item_names = enum_names("Item_Type")

pattern_text = rd(os.path.join(root, "src", "SPLORR.UI", "Pattern.vb"))
patterns = re.findall(r"^\s{4}(\w+)\s*$", pattern_text.split("Public Enum Pattern")[1].split("End Enum")[0], re.M)

out = ["package game", "", "// GENERATED by tools/gen/gen_ui.py from src/KordanorsCabal.UI and src/SPLORR.UI. Do not edit.", ""]
out.append("// The glyph (PETSCII character) names of the original Pattern enum; each value is the glyph index in font_data.odin.")
out.append("Glyph :: enum u8 {")
for p in patterns: out.append(f"\t{p},")
out.append("}")
out.append("")
out.append("SPRITE_SIZE :: 12")
out.append("// A sprite is 12 x 12 cells: '#' a solid cell, ' ' an empty cell drawn over the scene, '.' leaves the scene showing.")
out.append("Sprite :: struct { hue: Hue, rows: [SPRITE_SIZE]string }")
out.append("")

def sprites(text, key_names):
    found = {}
    for m in re.finditer(r"\{\s*(\d+)L?,\s*New Sprite\(\s*Hue\.(\w+),\s*LoadPixels\(\s*AddressOf PixelConvertor,((?:\s*\"[^\"]*\",?)+)\)\)", text):
        rows = re.findall(r'"([^"]*)"', m.group(3))
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), m.group(1)
        found[int(m.group(1))] = (snake(m.group(2)), rows)
    return found

cs = sprites(rd(os.path.join(ui, "CharacterSprites.vb")), character_names)
out.append("CHARACTER_SPRITES := #partial [Character_Type]Sprite{")
for i in sorted(cs):
    hue, rows = cs[i]
    out.append(f"\t.{character_names[i]} = {{.{hue}, {{" + ", ".join('"%s"' % r for r in rows) + "}},")
out.append("}")
out.append("")
rs = sprites(rd(os.path.join(ui, "RouteSprites.vb")), {})
hue, rows = rs[10]
out.append("// The sprite of route type 10, the portal.")
out.append(f"PORTAL_SPRITE := Sprite{{.{hue}, {{" + ", ".join('"%s"' % r for r in rows) + "}}")
out.append("")

out.append("Item_Display :: struct { present, flicker: bool, glyph: Glyph, x, y: u8, hue: Hue } // where an item lies on the dungeon floor")
out.append("ITEM_DISPLAY := #partial [Item_Type]Item_Display{")
desc = rd(os.path.join(ui, "ItemType", "Descriptor", "ItemTypeUIDescriptor.vb"))
for m in re.finditer(r"\{(\d+)L, New ItemTypeUIDescriptor\(Pattern\.(\w+), \((\d+), (\d+)\), Hue\.(\w+)\)\}", desc):
    out.append(f"\t.{item_names[int(m.group(1))]} = {{present = true, glyph = .{m.group(2)}, x = {m.group(3)}, y = {m.group(4)}, hue = .{snake(m.group(5))}}},")
orb = rd(os.path.join(ui, "ItemType", "Descriptor", "ElementalOrbUIDescriptor.vb"))
m = re.search(r"MyBase\.New\(Pattern\.(\w+), \((\d+), (\d+)\), Nothing\)", orb)
out.append(f"\t.Elemental_Orb = {{present = true, flicker = true, glyph = .{m.group(1)}, x = {m.group(2)}, y = {m.group(3)}}}, // the hue changes with the frame, see ORB_HUES")
hues = re.findall(r"Hue\.(\w+)", orb.split("Hues")[1].split("End Property")[0].split("Public Overrides")[0])
out.append("}")
out.append("ORB_HUES := [4]Hue{" + ", ".join("." + snake(h) for h in hues[:4]) + "}")
out.append("")
open(os.path.join(root, "odin", "game", "ui_data.odin"), "w").write("\n".join(out))
print("wrote odin/game/ui_data.odin:", len(cs), "character sprites,", len(patterns), "glyphs")
