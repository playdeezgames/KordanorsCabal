# One-off extractor (prototype of the task 8 constants extraction): PETSCII glyph bitmaps and the char -> glyph map.
import re
import os
HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "..", "src", "SPLORR.UI") + "/"
enum_text = open(src + "Pattern.vb", encoding="utf-8-sig").read()
names = re.findall(r"^\s{4}(\w+)\s*$", enum_text.split("Public Enum Pattern")[1].split("End Enum")[0], re.M)
assert len(names) == 128, len(names)
patterns = open(src + "Patterns.vb", encoding="utf-8-sig").read()
bitmaps = [tuple(map(int, m)) for m in re.findall(r"New PatternBitmap\((\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\)", patterns)]
assert len(bitmaps) == 128, len(bitmaps)
charmap = open(src + "Pattern.vb", encoding="utf-8-sig").read().split("CharacterPattern")[1]
charmap = "\n".join(re.sub(r"(?<=[,}])'.*$", "", line) for line in charmap.splitlines())  # drop VB comments
pairs = re.findall(r'\{("{4}|"[^"]"|"[^"]+")c, Pattern\.(\w+)\}', charmap)
glyph_of = {}
for lit, name in pairs:
    ch = '"' if lit == '""""' else lit[1:-1]
    glyph_of[ch] = names.index(name)
ascii_map = [255] * 128
for ch, g in glyph_of.items():
    if len(ch) == 1 and ord(ch) < 128:
        ascii_map[ord(ch)] = g
out = ["package game", "", "// GENERATED by tools/gen/gen_font.py from src/SPLORR.UI/Patterns.vb and Pattern.vb.", "// Bit 0 of each byte is the leftmost pixel.", ""]
out.append("GLYPHS :: [128][8]u8{")
for b in bitmaps:
    out.append("\t{" + ", ".join(map(str, b)) + "},")
out.append("}\n")
out.append("// ASCII -> glyph index (255 = no glyph). Lowercase letters share the uppercase glyphs.")
out.append("ASCII_GLYPH :: [128]u8{" + ", ".join(map(str, ascii_map)) + "}")
open(os.path.join(HERE, "..", "..", "odin", "game", "font_data.odin"), "w").write("\n".join(out) + "\n")
print("glyphs", len(bitmaps), "mapped ascii", sum(1 for x in ascii_map if x != 255), "space glyph", ascii_map[32], "A", ascii_map[65], "a", ascii_map[97])
